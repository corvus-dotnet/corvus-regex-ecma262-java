#!/usr/bin/env python3
"""Writes StringsGen.java, the properties of strings a pattern with the v flag may name, from strings_gen.rs of the
corvus-regex-ecma262 Rust crate (itself written by its tools/unicode/gen_strings.py from the emoji sequence files).

    python3 tools/unicode/gen_strings.py <path to strings_gen.rs> [output] [--check]
"""
import re
import sys

OUT = "src/main/java/io/github/corvusdotnet/regex/ecma262/StringsGen.java"


def main():
    args = [a for a in sys.argv[1:] if a != "--check"]
    source, output = args[0], (args[1] if len(args) > 1 else OUT)
    rs = open(source, encoding="utf-8").read()
    version = re.search(r'pub\(crate\) const VERSION: &str = "([^"]+)";', rs).group(1)
    rows = re.findall(r'\("([A-Za-z_]+)", "([^"]*)", "([^"]*)"\)', rs)
    assert len(rows) == 6, "the source has changed shape"
    lines = [
        "// Code generated by tools/unicode/gen_strings.py from strings_gen.rs of the corvus-regex-ecma262 Rust crate, from",
        "// emoji-sequences.txt and emoji-zwj-sequences.txt of Unicode %s. DO NOT EDIT." % version,
        "package io.github.corvusdotnet.regex.ecma262;",
        "",
        "/** The properties of strings of the v flag, generated. */",
        "final class StringsGen {",
        "    private StringsGen() {}",
        "",
        "    /** The version of Unicode the properties of strings are from. */",
        '    static final String VERSION = "%s";' % version,
        "",
        "    /**",
        "     * Each property of strings but RGI_Emoji (the union of them all): its name, its single code points as",
        "     * hexadecimal ranges, and its sequences as hexadecimal code points, a space between the code points of a",
        "     * sequence and a semicolon between sequences.",
        "     */",
        "    static final String[][] PROPERTIES = {",
    ]
    for name, points, seqs in rows:
        lines.append('        {"%s",' % name)
        lines.append('            "%s",' % points)
        lines.append('            "%s"},' % seqs)
    lines += ["    };", "}"]
    text = "\n".join(lines) + "\n"
    if "--check" in sys.argv:
        if open(output, encoding="utf-8").read() != text:
            sys.exit(f"{output} is not what {source} generates")
        return
    open(output, "w", encoding="utf-8").write(text)
    print(f"{output}: {len(rows)} properties of strings, Unicode {version}")


if __name__ == "__main__":
    main()
