#!/usr/bin/env python3
"""Expands the templates of src/template into one Java class per encoding, as Rust's monomorphisation makes one
matcher for each: UTF-8 over byte[] and UTF-16 over String. Java's generics cannot specialise on byte against char,
and an interface over the two would leave the matcher's every read a call the JIT may not inline, so the code is
written once and expanded here. The expanded files are checked in; CI runs this with --check.

In a template:
    $T$                  the class suffix, 8 or 16
    $INPUT$              the type of the text, byte[] or String
    $CODEC$              the class of the encoding's functions, Utf8 or Utf16
    $UTF8$               true or false
    AT(input, expr)      the unit at expr, as an int: (input[expr] & 0xFF) or input.charAt(expr)
    LEN(input)           the length of the text: input.length or input.length()
    //#if UTF8 ... //#else ... //#endif   lines for one encoding alone (the else is optional)

    python3 tools/expand.py [--check]
"""
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
TEMPLATES = os.path.join(ROOT, "src", "template")
OUT = os.path.join(ROOT, "src", "main", "java", "io", "github", "corvusdotnet", "regex", "ecma262")

ENCODINGS = {
    "8": {"$INPUT$": "byte[]", "$CODEC$": "Utf8", "$UTF8$": "true", "utf8": True},
    "16": {"$INPUT$": "String", "$CODEC$": "Utf16", "$UTF8$": "false", "utf8": False},
}


def call_args(text, start):
    """The arguments of the call whose '(' is at start, split at its top-level commas, and the index after its ')'."""
    depth, args, cur, k = 0, [], [], start + 1
    while k < len(text):
        c = text[k]
        if c == "(":
            depth += 1
        elif c == ")":
            if depth == 0:
                args.append("".join(cur).strip())
                return args, k + 1
            depth -= 1
        elif c == "," and depth == 0:
            args.append("".join(cur).strip())
            cur = []
            k += 1
            continue
        cur.append(c)
        k += 1
    raise SystemExit("an unclosed call in a template")


CALL = re.compile(r"\b(AT|LEN)\(")


def expand_calls(text, utf8):
    """Writes out every AT(...) and LEN(...), innermost first, as the encoding reads its text."""
    out, k = [], 0
    while True:
        m = CALL.search(text, k)
        if not m:
            out.append(text[k:])
            return "".join(out)
        out.append(text[k:m.start()])
        args, after = call_args(text, m.end() - 1)
        if m.group(1) == "AT":
            inp, idx = args[0], expand_calls(args[1], utf8)
            out.append(f"({inp}[{idx}] & 0xFF)" if utf8 else f"{inp}.charAt({idx})")
        else:
            out.append(f"{args[0]}.length" if utf8 else f"{args[0]}.length()")
        k = after


def expand(template, suffix):
    enc = ENCODINGS[suffix]
    lines, keep, stack = [], True, []
    for line in template.split("\n"):
        s = line.strip()
        if s.startswith("//#if "):
            want = s[6:].strip() == "UTF8"
            stack.append(want == enc["utf8"])
            continue
        if s == "//#else":
            stack[-1] = not stack[-1]
            continue
        if s == "//#endif":
            stack.pop()
            continue
        if all(stack):
            lines.append(line)
    text = "\n".join(lines)
    text = text.replace("$T$", suffix)
    for k in ("$INPUT$", "$CODEC$", "$UTF8$"):
        text = text.replace(k, enc[k])
    text = expand_calls(text, enc["utf8"])
    header = ("// Code generated by tools/expand.py from src/template/%s. DO NOT EDIT.\n" % os.path.basename(template_name))
    return header + text


template_name = ""


def main():
    global template_name
    check = "--check" in sys.argv
    stale = []
    for name in sorted(os.listdir(TEMPLATES)):
        if not name.endswith(".java.in"):
            continue
        template_name = name
        template = open(os.path.join(TEMPLATES, name), encoding="utf-8").read()
        base = name[: -len(".java.in")]
        for suffix in ENCODINGS:
            path = os.path.join(OUT, base + suffix + ".java")
            text = expand(template, suffix)
            if check:
                if not os.path.exists(path) or open(path, encoding="utf-8").read() != text:
                    stale.append(path)
            else:
                open(path, "w", encoding="utf-8").write(text)
                print(path)
    if stale:
        sys.exit("not what the templates expand to: " + ", ".join(stale))


if __name__ == "__main__":
    main()
