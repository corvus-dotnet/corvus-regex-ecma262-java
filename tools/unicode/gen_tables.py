#!/usr/bin/env python3
"""Writes TablesGen.java, the Unicode property tables of the engine, from tables_gen.rs of the corvus-regex-ecma262
Rust crate, which holds the same Unicode 17 data as the Go module and every other port.

Each table is a sorted list of inclusive ranges, the code points up to U+FFFF as 16-bit bounds and the rest as 32-bit
bounds (see Table.java). Array initialisers of that size would pass the 64 KB limit of a method's code, so each list
is written as a string constant (one char for a 16-bit bound, two for a 32-bit one) and decoded when the class loads.
The case mappings are written the same way, six chars a row.

    python3 tools/unicode/gen_tables.py <path to tables_gen.rs> [output]
"""
import re
import sys

OUT = "src/main/java/io/github/corvusdotnet/regex/ecma262/TablesGen.java"
# A string constant holds at most 65535 bytes of modified UTF-8, and a char takes up to three.
MAX_CHARS = 20000


def literal(chars):
    """A Java string literal of the code units. A \\u escape is read before the lexer, so the code units that would
    end a literal or a line are written with the ordinary escapes."""
    out = []
    for c in chars:
        if c == 0x0A:
            out.append("\\n")
        elif c == 0x0D:
            out.append("\\r")
        elif c == 0x22:
            out.append('\\"')
        elif c == 0x5C:
            out.append("\\\\")
        elif 0x20 <= c < 0x7F:
            out.append(chr(c))
        else:
            out.append("\\u%04X" % c)
    return '"' + "".join(out) + '"'


def strings(chars):
    """The code units as one literal, which must fit a constant."""
    assert len(chars) <= MAX_CHARS, "a table too long for one string constant"
    return literal(chars)


def ints(text):
    return [int(x, 0) for x in re.findall(r"-?0x[0-9A-Fa-f]+|-?\d+", text)]


def main():
    source = sys.argv[1]
    output = sys.argv[2] if len(sys.argv) > 2 else OUT
    rs = open(source, encoding="utf-8").read()
    version = re.search(r'pub\(crate\) const VERSION: &str = "([^"]+)";', rs).group(1)
    header = rs.split("\n")[0:2]

    tables = []
    for m in re.finditer(r"pub\(super\) static (\w+): Table = Table \{(.*?)\n\};", rs, re.S):
        # The two fields come in either order.
        fields = dict(re.findall(r"(r16|r32): &\[(.*?)\]", m.group(2), re.S))
        tables.append((m.group(1), ints(fields["r16"]), ints(fields["r32"])))

    functions = {}
    for m in re.finditer(r"pub\(super\) fn (\w+)\(name: &str\) -> Option<&'static Table> \{\s*match name \{(.*?)\n        _ => None,", rs, re.S):
        arms = []
        for arm in re.finditer(r'((?:"[^"]+"\s*\|\s*)*"[^"]+")\s*=>\s*Some\(&(\w+)\)', m.group(2)):
            arms.append((re.findall(r'"([^"]+)"', arm.group(1)), arm.group(2)))
        functions[m.group(1)] = arms

    script_names = [re.findall(r'"([^"]+)"', row) for row in
                    re.findall(r"&\[([^\]]*)\]", re.search(r"pub\(super\) static SCRIPT_NAMES: &\[&\[&str\]\] = &\[(.*?)\n\];", rs, re.S).group(1))]
    binary_names = re.findall(r'"([^"]+)"', re.search(r"pub\(super\) static BINARY_NAMES: &\[&str\] = &\[(.*?)\n\];", rs, re.S).group(1))

    cases = {}
    for name in ("CASE_FOLDS", "UPPER_CASES"):
        body = re.search(r"pub\(super\) static " + name + r": &\[CaseRange\] = &\[(.*?)\n\];", rs, re.S).group(1)
        cases[name] = [tuple(int(x, 0) for x in row) for row in
                       re.findall(r"CaseRange \{ first: (0x[0-9A-F]+|\d+), delta: (-?\d+), length: (\d+), mask: (\d+) \}", body)]

    assert tables and len(functions) == 4 and script_names and binary_names and all(cases.values()), "the source has changed shape"

    java_name = {"category_table": "categoryTable", "binary_table": "binaryTable", "script_table": "scriptTable",
                 "script_extensions_table": "scriptExtensionsTable"}
    lines = [
        "// Code generated by tools/unicode/gen_tables.py from tables_gen.rs of the corvus-regex-ecma262 Rust crate, which",
        "// " + header[0].removeprefix("// ").replace("Code generated by", "was generated by") if header else "",
        "// " + header[1].removeprefix("// ") if len(header) > 1 else "",
        "package io.github.corvusdotnet.regex.ecma262;",
        "",
        "/** The Unicode property tables and case mappings, generated. */",
        "final class TablesGen {",
        "    private TablesGen() {}",
        "",
        "    /** The version of Unicode the tables hold. */",
        '    static final String VERSION = "%s";' % version,
        "",
    ]
    for fn, arms in functions.items():
        lines.append("    static Table %s(String name) {" % java_name[fn])
        lines.append("        switch (name) {")
        for names, table in arms:
            for n in names:
                lines.append('            case "%s":' % n)
            lines.append("                return %s;" % table)
        lines.append("            default:")
        lines.append("                return null;")
        lines.append("        }")
        lines.append("    }")
        lines.append("")
    lines.append("    /** Every name of every script: the long name of each, followed by its aliases. */")
    lines.append("    static final String[][] SCRIPT_NAMES = {")
    for row in script_names:
        lines.append("        {" + ", ".join('"%s"' % n for n in row) + "},")
    lines.append("    };")
    lines.append("")
    lines.append("    /** The canonical name of every binary property that has a table. */")
    lines.append("    static final String[] BINARY_NAMES = {")
    for n in binary_names:
        lines.append('        "%s",' % n)
    lines.append("    };")
    lines.append("")
    for name, rows in cases.items():
        chars = []
        for first, delta, length, mask in rows:
            d = delta & 0xFFFFFFFF
            chars += [first >> 16, first & 0xFFFF, d >> 16, d & 0xFFFF, length, mask]
        lines.append("    static final int[] %s = Table.caseRanges(%s);" % (name, strings(chars)))
    lines.append("")
    for name, r16, r32 in tables:
        assert all(0 <= v <= 0xFFFF for v in r16) and all(0x10000 <= v <= 0x10FFFF for v in r32), name
        r32chars = []
        for v in r32:
            r32chars += [v >> 16, v & 0xFFFF]
        lines.append("    static final Table %s = Table.of(%s, %s);" % (name, strings(r16), strings(r32chars)))
    lines.append("}")
    text = "\n".join(l for l in lines if l is not None) + "\n"
    if "--check" in sys.argv:
        current = open(output, encoding="utf-8").read()
        if current != text:
            sys.exit(f"{output} is not what {source} generates")
        return
    open(output, "w", encoding="utf-8").write(text)
    print(f"{output}: {len(tables)} tables, {len(script_names)} scripts, Unicode {version}")


if __name__ == "__main__":
    main()
