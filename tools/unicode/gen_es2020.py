#!/usr/bin/env python3
"""Writes Es2020.java, the Unicode property names and values of the tables of ECMAScript 2020, from es2020.rs of the
corvus-regex-ecma262 Rust crate, so every engine's 2020 grammar knows the same names. Each list is written as one
string of names joined by spaces and read into a set when the class loads, which keeps the class's methods small.

    python3 tools/unicode/gen_es2020.py <path to es2020.rs> [output] [--check]
"""
import re
import sys

OUT = "src/main/java/io/github/corvusdotnet/regex/ecma262/Es2020.java"


def names(rs, rust_fn):
    """The names a Rust `matches!` of the function lists."""
    m = re.search(r"fn " + rust_fn + r"\(name: &str\) -> bool \{\s*matches!\(\s*name,(.*?)\)\s*\}", rs, re.S)
    if m is None:
        sys.exit(f"es2020.rs has no {rust_fn}: the generator needs updating for the crate's file")
    found = re.findall(r'"([^"]*)"', m.group(1))
    assert found and all(" " not in n for n in found), rust_fn
    return found


def wrapped(values, indent):
    """The names joined by spaces, as string literals of at most 120 columns joined by +."""
    lines, line = [], ""
    for v in values:
        piece = v + " "
        if len(indent) + len(line) + len(piece) + 5 > 120:
            lines.append(line)
            line = ""
        line += piece
    lines.append(line.rstrip(" "))
    return ("\n" + indent + "+ ").join('"%s"' % l for l in lines)


def main():
    args = [a for a in sys.argv[1:] if a != "--check"]
    source = args[0]
    output = args[1] if len(args) > 1 else OUT
    rs = open(source, encoding="utf-8").read()
    tables = [("NON_BINARY", "The non-binary properties.", names(rs, "non_binary")),
              ("BINARY", "The binary properties.", names(rs, "binary")),
              ("CATEGORY", "The General_Category values.", names(rs, "category")),
              ("SCRIPT", "The Script values.", names(rs, "script"))]
    lines = [
        "// Code generated by tools/unicode/gen_es2020.py from es2020.rs of the corvus-regex-ecma262 Rust crate. DO NOT EDIT.",
        "package io.github.corvusdotnet.regex.ecma262;",
        "",
        "import java.util.Set;",
        "",
        "/**",
        " * The Unicode property names and values of the tables of ECMAScript 2020 (ECMA-262, 11th edition), the only ones",
        " * its grammar knows whatever the version of Unicode: tc39/ecma262 at the tag es2020, every name and alias of each.",
        " */",
        "final class Es2020 {",
        "    private Es2020() {}",
        "",
    ]
    for name, doc, values in tables:
        lines.append(f"    /** {doc} */")
        lines.append(f"    private static final Set<String> {name} = Set.of(")
        lines.append("            (" + wrapped(values, "             ") + ").split(\" \"));")
        lines.append("")
    lines += [
        "    /**",
        "     * Whether the expression between the braces of {@code \\p{...}} names a property, and a value of it, of the",
        "     * tables: a name and a value joined by {@code =}, or the lone name of a General_Category value or of a binary",
        "     * property.",
        "     */",
        "    static boolean hasProperty(String expr) {",
        "        int eq = expr.indexOf('=');",
        "        if (eq < 0) {",
        "            return CATEGORY.contains(expr) || BINARY.contains(expr);",
        "        }",
        "        String name = expr.substring(0, eq);",
        "        String value = expr.substring(eq + 1);",
        "        if (name.equals(\"General_Category\") || name.equals(\"gc\")) {",
        "            return CATEGORY.contains(value);",
        "        }",
        "        return NON_BINARY.contains(name) && SCRIPT.contains(value);",
        "    }",
        "}",
    ]
    text = "\n".join(lines) + "\n"
    count = sum(len(v) for _, _, v in tables)
    if "--check" in sys.argv:
        if open(output, encoding="utf-8").read() != text:
            sys.exit(f"{output} is not what {source} generates")
        return
    with open(output, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"{output}: {count} names")


if __name__ == "__main__":
    main()
