#!/usr/bin/env python3
"""Writes the tables of string literals of a Rust test file (const NAME: &[...] = &[...];) as Java arrays, for the
tests ported from the Rust crate. Each tuple becomes an Object[] of Strings and String[]s; a bare string table becomes
a String[].

    python3 tools/tests/rust_tables.py <file.rs> <Class> > src/test/java/.../<Class>.java
"""
import re
import sys


def rust_string(s, k):
    """The string literal at s[k], and the index after it."""
    if s.startswith("r#", k) or s.startswith('r"', k):
        hashes = 0
        j = k + 1
        while s[j] == "#":
            hashes += 1
            j += 1
        assert s[j] == '"'
        end = s.index('"' + "#" * hashes, j + 1)
        return s[j + 1:end], end + 1 + hashes
    assert s[k] == '"', s[k:k + 40]
    out = []
    j = k + 1
    while True:
        c = s[j]
        if c == '"':
            return "".join(out), j + 1
        if c != "\\":
            out.append(c)
            j += 1
            continue
        e = s[j + 1]
        if e == "u":
            close = s.index("}", j)
            out.append(chr(int(s[j + 3:close], 16)))
            j = close + 1
        elif e == "x":
            out.append(chr(int(s[j + 2:j + 4], 16)))
            j += 4
        elif e == "\n":
            j += 2
            while s[j] in " \t\n":
                j += 1
        else:
            out.append({"n": "\n", "r": "\r", "t": "\t", "0": "\0", "\\": "\\", '"': '"', "'": "'"}[e])
            j += 2


def java_string(v):
    out = ['"']
    for ch in v:
        cp = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif 0x20 <= cp < 0x7F:
            out.append(ch)
        elif cp > 0xFFFF:
            cp -= 0x10000
            out.append("\\u%04X\\u%04X" % (0xD800 + (cp >> 10), 0xDC00 + (cp & 0x3FF)))
        else:
            out.append("\\u%04X" % cp)
    out.append('"')
    return "".join(out)


def value(s, k):
    """A string, a tuple or an array at s[k] (after white space), and the index after it."""
    while s[k] in " \t\n,":
        k += 1
    if s.startswith("&[", k) or s[k] == "[" or s[k] == "(":
        close = {"(": ")", "[": "]"}[s[k + 1] if s[k] == "&" else s[k]]
        k += 2 if s[k] == "&" else 1
        items = []
        while True:
            while s[k] in " \t\n,":
                k += 1
            if s.startswith("//", k):
                k = s.index("\n", k)
                continue
            if s[k] == close:
                return (tuple(items) if close == ")" else list(items)), k + 1
            v, k = value(s, k)
            items.append(v)
    return rust_string(s, k)


def java(v, indent):
    if isinstance(v, str):
        return java_string(v)
    if isinstance(v, list) and all(isinstance(x, str) for x in v):
        return "new String[] {" + ", ".join(java_string(x) for x in v) + "}"
    if isinstance(v, tuple):
        return "{" + ", ".join(java(x, indent) for x in v) + "}"
    raise SystemExit("unexpected " + repr(v)[:80])


def main():
    src = open(sys.argv[1], encoding="utf-8").read()
    cls = sys.argv[2]
    print("// Code generated by tools/tests/rust_tables.py from " + sys.argv[1].split("/")[-1] + ". DO NOT EDIT.")
    print("package io.github.corvusdotnet.regex.ecma262;")
    print()
    print("final class %s {" % cls)
    print("    private %s() {}" % cls)
    for m in re.finditer(r"^const ([A-Z0-9_]+): ([^=]+)=\s*", src, re.M):
        name, ty = m.group(1), m.group(2).strip()
        v, _ = value(src, m.end())
        print()
        if isinstance(v, str):
            print("    static final String %s = %s;" % (name, java_string(v)))
        elif all(isinstance(x, str) for x in v):
            print("    static final String[] %s = {" % name)
            for x in v:
                print("        " + java_string(x) + ",")
            print("    };")
        else:
            print("    static final Object[][] %s = {" % name)
            for x in v:
                print("        " + java(x, 8) + ",")
            print("    };")
    print("}")


main()
